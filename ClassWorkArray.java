public class ClassWorkArray{
	public static void main(String[] args){
		
		int[] values = {8,2,5,12,6,3,7,11,13,4};
		
		for(int i = 1; i < 10; i++){
			System.out.println(values[i]);
		}
		System.out.println("--------------------");
		if(i % 2 == 0){
			System.out.print(values[i]);
		}
		else{
			System.out.println("");
		}
	}
}